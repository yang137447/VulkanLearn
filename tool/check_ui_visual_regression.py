"""Visual regression check for the editor chrome: menus, tabs and the product name.

The pixel probes in this directory prove that *something* is drawn at a coordinate.
They cannot read what the text says, and they reported a 94px selected tab as
"present" while it rendered completely blank. A vision model closes that gap: it
reports the labels it actually sees.

Two invariants are checked, and neither expectation is hand-written into this file --
both are extracted from their source of truth so they cannot drift:

1. Every menu title and workspace tab label present in `ui/editor-workspace.rml` must be
   readable in the captured frame.
2. Every tab the model reports must carry text. Asking the model to name the tabs and
   comparing its list against the authored labels catches a tab that renders as an icon
   with no label -- the defect this check exists for.

Usage, in three steps because the vision model lives behind the harness:

    py -3 tool/check_ui_visual_regression.py prompt      # writes the prompt to hand over
    <run that prompt against deepseek-v4-flash-vision-exp, save its JSON reply>
    py -3 tool/check_ui_visual_regression.py check --reply <file>

The middle step is documented in `documents/contracts/testing.md`. `check` exits
non-zero on any mismatch, so it can gate.
"""
import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RML = REPO / "ui" / "editor-workspace.rml"

MENU_TITLE = re.compile(r'class="menu-title"[^>]*>([^<]+)<')
# Capture the whole opening tag and the inner markup separately. Starting the group in
# the middle of the attribute list makes the capture pick up trailing attributes and the
# tag's own closing ">", so the extracted label came out as
# 'data-action="workspace-content">Content Browser' instead of the label.
WORKSPACE_TAB = re.compile(
    r'<button\s+([^>]*?id="(workspace-[a-z]+-tab)"[^>]*data-workspace-panel="([a-z]+)"[^>]*)>'
    r'(.*?)</button>', re.S)
TITLE_ATTR = re.compile(r'title="([^"]+)"')
INNER_TAG = re.compile(r"<[^>]+>")
PRODUCT_NAME = re.compile(r"<h1>([^<]+)</h1>")

# The resource tab's label is authored in the RML as a `title` attribute and regenerated
# at runtime by BaseTabMarkup in source/editor/ui/editorDockingController.cpp, so the two
# must agree. Recorded so an edit that changes one but not the other is visible here.
GENERATED_TAB_LABELS = {
    "Asset Editor": "title attr in ui/editor-workspace.rml; regenerated by "
                    "BaseTabMarkup in source/editor/ui/editorDockingController.cpp",
}

DOCUMENT_COMMANDS = ("Save", "Revert", "Validate", "Reload", "Reset All")

REPLY_SCHEMA_HINT = """Reply with ONLY a JSON object, no prose and no code fence:
{
  "menu": ["<menu title>", ...],
  "product": "<product name>",
  "tabs": [{"label": "<text you can read>", "has_text": true|false}, ...],
  "toolbar_between_product_and_buttons": ["<text of any button there>", ...]
}
`tabs` must list every tab you can see, in reading order. If a tab shows an icon but no
readable text, include it with "has_text": false and an empty label -- do not omit it
and do not invent a name for it."""


def extract_expectations():
    """Read the authored labels out of the workspace markup."""
    text = RML.read_text(encoding="utf-8")
    menus = MENU_TITLE.findall(text)
    product = PRODUCT_NAME.search(text)
    if not menus or product is None:
        raise SystemExit("could not extract menu/product expectations from %s" % RML)

    tabs = []
    sources = {}
    for attributes, tab_id, panel, inner in WORKSPACE_TAB.findall(text):
        # Prefer the authored `title`: for the resource tab the visible text is produced
        # at runtime, so the title is the stable statement of intent.
        title = TITLE_ATTR.search(attributes)
        label = title.group(1).strip() if title else INNER_TAG.sub("", inner).strip()
        if not label:
            raise SystemExit("workspace tab %s has no readable label in %s" % (tab_id, RML))
        tabs.append(label)
        sources[label] = "%s (%s)" % (RML.relative_to(REPO).as_posix(), panel)

    for label, source in GENERATED_TAB_LABELS.items():
        if label not in tabs:
            tabs.append(label)
        sources.setdefault(label, source)

    return {"menus": menus, "product": product.group(1).strip(),
            "tabs": tabs, "tab_sources": sources}


def default_shot():
    """The most recent capture from the screenshot probe, if one exists."""
    root = REPO.parent / "VukanLearnResources" / "Generated" / "Screenshots"
    if not root.is_dir():
        return None
    shots = sorted(root.glob("*.bmp"), key=lambda p: p.stat().st_mtime, reverse=True)
    return shots[0] if shots else None


def fail(message):
    print("FAIL: %s" % message, file=sys.stderr)
    return 1


def cmd_prompt(args):
    expectations = extract_expectations()
    shot = Path(args.shot) if args.shot else default_shot()
    if shot is None or not shot.is_file():
        return fail("no screenshot found; capture one first (see documents/contracts/testing.md)")

    print("Expectations extracted from the repository, not hand-written here:")
    print("  menus   : %s" % ", ".join(expectations["menus"]))
    print("  product : %s" % expectations["product"])
    print("  tabs    : %s" % ", ".join(expectations["tabs"]))
    for label in expectations["tabs"]:
        print("      %-18s <- %s" % (label, expectations["tab_sources"].get(label, "?")))
    print()
    print("Screenshot: %s (%d bytes)" % (shot, shot.stat().st_size))
    print()
    print("=" * 72)
    print("PROMPT TO GIVE deepseek-v4-flash-vision-exp")
    print("=" * 72)
    print("You have a read_image tool. Read exactly this file:\n%s\n\n"
          "It is a screenshot of a game-engine editor UI. BMP is not accepted by "
          "read_image -- convert it to PNG first, then read the PNG.\n\n"
          "Report only what you can actually see. This prompt does not tell you the "
          "expected answers, so do not try to match anything; if you cannot read the "
          "image, reply exactly \"I CANNOT SEE THE IMAGE\" and nothing else.\n\n%s"
          % (shot, REPLY_SCHEMA_HINT))
    print("=" * 72)
    print()
    print("Save the model's JSON reply to a file, then run:")
    print("  py -3 tool/check_ui_visual_regression.py check --reply <file>")
    return 0


def cmd_check(args):
    expectations = extract_expectations()
    try:
        reply = json.loads(Path(args.reply).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as error:
        return fail("could not read the model reply as JSON: %s" % error)
    if not isinstance(reply, dict):
        return fail("model reply is not a JSON object")

    problems = []

    # The model is not told the expected answers, so a mismatch means either the UI
    # changed or the model misread. Both need a human look, so both fail.
    menu = [str(item).strip() for item in reply.get("menu", [])]
    for title in expectations["menus"]:
        if title not in menu:
            problems.append("menu title not readable in the frame: %r (saw %s)" % (title, menu))
    for title in menu:
        if title not in expectations["menus"]:
            problems.append("frame shows a menu title the repository does not declare: %r" % title)

    product = str(reply.get("product", "")).strip()
    if product != expectations["product"]:
        problems.append("product name mismatch: frame %r vs repository %r"
                        % (product, expectations["product"]))

    seen = []
    for entry in reply.get("tabs", []):
        if not isinstance(entry, dict):
            problems.append("tab entry is not an object: %r" % (entry,))
            continue
        label = str(entry.get("label", "")).strip()
        if not bool(entry.get("has_text")) or not label:
            problems.append("tab renders with no readable text: %r -- every tab must carry "
                            "a label" % (label or entry))
        else:
            seen.append(label)
    for label in expectations["tabs"]:
        if label not in seen:
            problems.append("authored tab label not readable in the frame: %r (saw %s)"
                            % (label, seen))
    for label in seen:
        if label not in expectations["tabs"]:
            problems.append("frame shows a tab the repository does not declare: %r" % label)

    # The duplication this check was added alongside: document commands belong to the
    # menus, not to a second row of toolbar buttons.
    between = [str(item).strip() for item in reply.get("toolbar_between_product_and_buttons", [])]
    for command in DOCUMENT_COMMANDS:
        if command in between:
            problems.append("toolbar restates the menu command %r between the product name "
                            "and the right-hand buttons" % command)

    print("menus   : %s" % (menu or "(none reported)"))
    print("product : %r" % product)
    print("tabs    : %s" % (seen or "(none reported)"))
    print("between : %s" % (between or "(nothing)"))
    print()
    if problems:
        for problem in problems:
            print("  - %s" % problem, file=sys.stderr)
        return fail("%d visual regression(s)" % len(problems))
    print("UI visual regression check passed (%d menu titles, %d tabs, no unnamed tab)"
          % (len(expectations["menus"]), len(seen)))
    return 0


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    prompt = sub.add_parser("prompt", help="emit the prompt to hand to the vision model")
    prompt.add_argument("--shot", help="screenshot to read (default: newest capture)")
    prompt.set_defaults(func=cmd_prompt)
    check = sub.add_parser("check", help="validate the model's JSON reply")
    check.add_argument("--reply", required=True, help="file containing the model's JSON reply")
    check.set_defaults(func=cmd_check)
    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
